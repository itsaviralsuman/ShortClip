export function generateTranscriptForDuration(
  durationSeconds: number,
  language: VideoLanguage = 'hinglish'
): TranscriptWord[] {
  const pool =
    language === 'hindi'
      ? HINDI_WORDS_POOL
      : language === 'hinglish'
      ? HINGLISH_WORDS_POOL
      : ENGLISH_WORDS_POOL;

  const words: TranscriptWord[] = [];
  const wordsCount = Math.max(12, Math.floor(durationSeconds * 2.4)); // ~2.4 words per second
  const timePerWord = durationSeconds / wordsCount;

  for (let i = 0; i < wordsCount; i++) {
    const item = pool[i % pool.length];
    const start = parseFloat((i * timePerWord).toFixed(2));
    const end = parseFloat(((i + 1) * timePerWord - 0.05).toFixed(2));

    words.push({
      id: `w_${i + 1}`,
      text: item.text,
      start,
      end,
      speaker: i % 14 < 8 ? 'Speaker 1' : 'Speaker 2',
      highlightColor: item.highlight ? (i % 2 === 0 ? '#FACC15' : '#4ADE80') : undefined,
      emoji: item.emoji || undefined
    });
  }

  return words;
}
